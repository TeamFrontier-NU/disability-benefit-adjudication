"""Write study/content/texts/case_terms.yaml: for each case, the terms from terms.yaml whose
`match` pattern occurs in that case's own medical records (English sources, the screen sheet
excluded). The list follows what the records say, in bank order; it never uses the answer key.

Usage: python study/materials/make_case_terms.py
"""
from __future__ import annotations

import re
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
TEXTS = HERE.parent / "content" / "texts"


def main() -> None:
    bank = yaml.safe_load((TEXTS / "terms.yaml").read_text(encoding="utf-8"))["terms"]
    out = {}
    for case in sorted(p for p in (HERE / "cases").iterdir() if (p / "records").is_dir()):
        text = "\n".join(f.read_text(encoding="utf-8") for f in sorted((case / "records").glob("*.rec.md"))
                         if not f.name.startswith("00_screen"))
        out[case.name] = [k for k, t in bank.items() if re.search(t["match"], text, re.I if k not in ("levels", "abbr", "sections") else 0)]
        print(case.name, len(out[case.name]), " ".join(out[case.name]))
    head = "# Generated by study/materials/make_case_terms.py. Do not edit by hand.\n"
    (TEXTS / "case_terms.yaml").write_text(head + yaml.safe_dump(out, sort_keys=True), encoding="utf-8")


if __name__ == "__main__":
    main()
